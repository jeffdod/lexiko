#!/usr/bin/env python3
"""Write sw-assets.js: the list of files to precache + a content-hash version.
Run after ANY change to the app files, data or fonts:  python3 tools/build_sw.py"""
import os, hashlib, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE = ['index.html', 'manifest.webmanifest', 'favicon.svg', 'favicon.ico', 'css', 'js', 'data', 'fonts',
           'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png',
           'icons/favicon-16.png', 'icons/favicon-32.png']
files = []
for item in INCLUDE:
    p = os.path.join(ROOT, item)
    if os.path.isdir(p):
        for d, _, fs in os.walk(p):
            files += [os.path.relpath(os.path.join(d, f), ROOT) for f in fs if not f.endswith('.txt') or item != 'fonts' or f == 'OFL.txt']
    elif os.path.exists(p): files.append(item)
    else: raise SystemExit('missing: ' + item)
files = sorted(set(f.replace(os.sep, '/') for f in files))
h = hashlib.sha1()
for f in files:
    b = open(os.path.join(ROOT, f), 'rb').read()
    if f.endswith(('.html', '.js', '.css', '.json', '.svg', '.webmanifest')): b = b.replace(b'\r\n', b'\n')   # same hash on Windows checkouts (CRLF)
    h.update(f.encode()); h.update(b)
version = h.hexdigest()[:10]
assets = ['./'] + files
open(os.path.join(ROOT, 'sw-assets.js'), 'w').write(
    '// generated by tools/build_sw.py — do not edit\nself.LEXIKO_VERSION = %s;\nself.LEXIKO_ASSETS = %s;\n' % (json.dumps(version), json.dumps(assets, indent=1)))
print('sw-assets.js: %d files, version %s, %.2f MB' % (len(assets), version, sum(os.path.getsize(os.path.join(ROOT, f)) for f in files) / 1048576))
